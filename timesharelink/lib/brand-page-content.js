/** slug로 브랜드 전체 데이터(기본 + 페이지 콘텐츠) 조회 */
export function getBrandPageData(slug) {
  const koreanName = BRAND_SLUG_MAP[slug];
  if (!koreanName) return null;
  const baseSite = BRAND_SITES.find((s) => s.name === koreanName);
  const pageContent = BRAND_PAGE_DATA[slug];
  if (!baseSite || !pageContent) return null;
  return { ...baseSite, ...pageContent, slug, koreanName };
}

/** 모든 유효한 slug 목록 (generateStaticParams용) */
export function getAllBrandSlugs() {
  return Object.keys(BRAND_SLUG_MAP);
}
